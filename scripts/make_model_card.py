import os

from common import *


def main():
    rows = [r for r in load_rows() if r.get("regime") == BEST_REGIME]
    if not rows:
        raise SystemExit(f"No row with regime={BEST_REGIME!r} in {RESULTS_JSON}")
    r = rows[-1]
    m = r.get("metrics", {})
    pc = r.get("per_class", {})
    lat = r.get("latency_cpu_ms") or {}
    dep = r.get("deploy_benchmark")
    per_class = md_table(["class", "precision", "recall", "F1", "support"],
                         [[c, fmt(v["precision"], 3), fmt(v["recall"], 3), fmt(v["f1"], 3), v["support"]] for c, v in pc.items()]) if pc else "<<per-class table>>"
    dep_txt = ""
    if dep:
        dep_txt = md_table(["variant", "size MB", "latency ms", "accuracy", "acc drop pp"],
                           [[v["variant"], fmt(v["size_mb"], 2), fmt(v["latency_mean_ms"], 2), fmt(v["accuracy"]), f"{v['acc_drop_pp']:+.2f}"]
                            for v in dep["variants"]])

    card = f"""# Model card - MobileNetV2 photo-quality classifier ({BEST_REGIME})

## Intended use
- **Task:** first gate of the document-photo pipeline - classify an uploaded photo as suitable / defective before OCR.
- **Intended users / setting:** <<who calls it, on what device, what image size/format>>
- **Out of scope:** <<e.g. photos of other document types, very low-res images, defects not in the training set, any use as the only quality check without operator review>>

## Training data
- Source: <<synthetic images generated by ... ; number of images per class>>; split 70/15/15, seed {r.get('seed')}.
- Classes: <<list>>; known imbalance: <<...>>
- Augmentation: <<none / 5C glare augmentation on train only>>

## Model and training
- MobileNetV2 (ImageNet pretrained), head: GAP -> Dense({HEAD_UNITS}) -> Dropout({DROPOUT}) -> sigmoid/softmax.
- Regime: {BEST_REGIME}; epochs <= {r.get('epochs_max')}, patience {r.get('patience')}, batch {r.get('batch')}; lr: <<{r.get('lr', LR_HEAD)}>>.

## Metrics (test split, never used for tuning)
| accuracy | macro precision | macro recall | macro F1 |
|---|---|---|---|
| {fmt(m.get('accuracy'))} | {fmt(m.get('precision_macro'))} | {fmt(m.get('recall_macro'))} | {fmt(m.get('f1_macro'))} |

{per_class}

Operating threshold: **{r.get('chosen_threshold', '0.5 (default)')}** (chosen on validation, see `reports/bonus_threshold_memo.md`).

## Latency and size
- Keras, CPU, batch 1: {fmt(lat.get('mean_ms'), 2) if lat else '<<ms>>'} ms mean ({lat.get('warmup', 20)} warm-up + {lat.get('runs', 100)} timed runs); size {fmt(r.get('model_size_mb'), 2) if r.get('model_size_mb') else '<<MB>>'} MB.
{dep_txt}

## Limitations
- **Synthetic-to-real gap:** the capstone report measured 2.8-5.8 % lower performance on real photos than on synthetic ones; expect this gap here too. <<your own evidence if any>>
- **Weakest class:** <<glare - give F1 and what typically goes wrong, link to errors/gallery.png>>
- **Conditions not tested:** <<lighting, camera types, motion blur, partial occlusion, resolutions, ...>>
- **Threshold dependence:** false accepts and false rejects trade off; the chosen threshold was tuned for <<...>> and must be re-checked if the data distribution changes.

## Ethics and misuse
- <<Photos of documents/cards may contain personal data: how they are stored, who sees rejected images, retention.>>
- <<Risk of silent misuse outside the tested conditions; who is responsible for monitoring; what happens when the model is wrong (operator rework vs user retake).>>
- <<Fairness/accessibility: does rejecting photos burden users with older phones or poor lighting?>>

## Maintenance
- Reproduce: see README (seed {r.get('seed')}, split description, commands). Re-evaluate when the data source changes.
"""
    ensure(REPORTS_DIR)
    open(os.path.join(REPORTS_DIR, "model_card.md"), "w").write(card)
    print("reports/model_card.md written - fill the <<...>> parts, they are the actual content of the card.")


if __name__ == "__main__":
    main()
